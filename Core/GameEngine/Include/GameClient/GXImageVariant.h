// GeneralsX @tweak Claude 03/10/2026 Occupancy pips at 7x16 / 10x24 above 1080p, hand-drawn, never stretched (owner,
// 03/10/2026: "C" at 1440p with the black rim from "E", "D" at 4K; "make sure everything graphics wise works outside
// 1440p on all displays").
//
// Retail draws SCPPipFull / SCPPipEmpty (5x12) 1:1 at every resolution, so at 1440p the pips are a quarter smaller next to
// the unit than at 1080p and at 4K half. Stretching the 5x12 bitmap blurs it (players preferred the crisp retail pip,
// 02/10/2026), so the larger sizes are separate hand-drawn art in the retail palette (!GXUIHD.big, generated by
// scripts/build/make-gxuihd-archive.py) and the engine picks the one that fits, drawn at its own size.
//
// THE SIZE RULE, by the render's height in PIXELS (TheDisplay->getHeight(): physical pixels on every platform - the
// Windows exe is PerMonitorV2 DPI-aware, macOS and iPadOS render at backing-pixel density):
//   - under 1437 px tall (800x600 .. 1920x1080, 2560x1080, 1920x1200): retail 5x12, exactly as today;
//   - 1437 .. 2159 px (2560x1440, 3440x1440, 5120x1440, 2560x1600, 1800p): 7x16, the share of the screen retail has at 1080p;
//   - 2160 px and up (4K, 5K, 8K): 10x24.
// The step is height * 100 / 1080 against each variant's scale x 100; between steps the lower art is held and drawn 1:1.
// Width never enters: the unit on screen scales with the height, so an ultrawide draws what its height draws. A missing
// variant (archive off, older install) falls back to the largest one present, then to retail.
//
// Header-only and pure: both games' Drawable.cpp and scripts/test/image-variant-test.cpp.

#pragma once

/// The hand-drawn pip variants, as their scale x 100 against retail's 5x12: SCPPipFull@133 is 7x16, @200 is 10x24.
enum { GX_PIP_VARIANTS = 2 };
static const int GX_PIP_VARIANT_PCT[GX_PIP_VARIANTS] = { 133, 200 };

/// Which pip art to draw on a render `heightPx` pixels tall: the index of the largest variant whose scale is at or under
/// heightPx * 100 / 1080 and whose art is `present`, or -1 for retail's 5x12 (also for a zero or negative height).
inline int gxPickPipVariant( int heightPx, const bool present[GX_PIP_VARIANTS] )
{
	const long long scale = (long long)heightPx * 100 / 1080;
	int best = -1;
	for (int i = 0; i < GX_PIP_VARIANTS; ++i)
		if (present[i] && GX_PIP_VARIANT_PCT[i] <= scale && (best < 0 || GX_PIP_VARIANT_PCT[i] > GX_PIP_VARIANT_PCT[best]))
			best = i;
	return best;
}

/// Rows the empty pip is drawn below the full one: retail's art 1 row down (as today), the hand-drawn art top-aligned.
inline int gxPipEmptyYOffset( int variant )
{
	return variant < 0 ? 1 : 0;
}
